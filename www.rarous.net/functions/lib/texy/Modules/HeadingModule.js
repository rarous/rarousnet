/**
 * Processes heading syntax: underlined and surrounded (port of
 * Texy\Modules\HeadingModule).
 *
 * Level balancing, {toc} hoisting and ID generation are the HeadingPass
 * transform in the reference and are out of scope; this module stores the
 * preliminary level and exposes the configuration for consumers running
 * their own passes.
 */

import { Module } from './Module.js';
import { Syntax } from '../Syntax.js';
import { ModifierHAlign } from '../Patterns.js';
import { Modifier } from '../Modifier.js';
import { HeadingNode, HeadingType } from '../nodes.js';

export class HeadingModule extends Module
{
	constructor(texy)
	{
		super();
		this.texy = texy;

		/** level of top heading, 1..6 (used by the transform pass) */
		this.top = 1;

		/** surrounded headings: more #### means higher heading */
		this.moreMeansHigher = true;

		/** balancing mode: HeadingModule.Dynamic | HeadingModule.Fixed */
		this.balancing = HeadingModule.Dynamic;

		/** @type {Object<string, number>} when balancing = Fixed */
		this.levels = { '#': 0, '*': 1, '=': 2, '-': 3 };

		/** generate ID for headings? (transform pass) */
		this.generateID = false;

		/** prefix for autogenerated IDs */
		this.idPrefix = 'toc-';
	}


	beforeParse()
	{
		this.texy.addBlockSyntax(
			Syntax.HeadingUnderlined,
			String.raw`~^
				( \S .{0,1000} )                 # heading text (1)
				` + ModifierHAlign + String.raw`? # modifier (2)
				\n
				( \#{3,}+ | \*{3,}+ | ={3,}+ | -{3,}+ )  # underline characters (3)
			$~mUx`,
			(context, matches, offsets) => this.parseUnderline(context, matches, offsets),
		);

		this.texy.addBlockSyntax(
			Syntax.HeadingSurrounded,
			String.raw`~^
				( \#{2,}+ | ={2,}+ )             # opening characters (1)
				(.+)                             # heading text (2)
				` + ModifierHAlign + String.raw`? # modifier (2)
			$~mUx`,
			(context, matches, offsets) => this.parseSurround(context, matches, offsets),
		);
	}


	/**
	 * Parses underlined heading.
	 */
	parseUnderline(context, matches, offsets)
	{
		const [, mContent, mMod, mLine] = matches;
		const level = this.levels[mLine[0]];
		const contentOffset = offsets[1];
		return new HeadingNode(
			context.parseInline(mContent.trim(), contentOffset),
			level,
			HeadingType.Underlined,
			Modifier.parse(mMod, offsets[2] ?? null),
			{ offset: offsets[0], length: matches[0].length },
		);
	}


	/**
	 * Parses surrounded heading.
	 */
	parseSurround(context, matches, offsets)
	{
		let [, mLine, mContent, mMod] = matches;
		let level = Math.min(7, Math.max(2, mLine.length));
		level = this.moreMeansHigher ? 7 - level : level - 2;
		mContent = mContent.replace(new RegExp('[' + mLine[0].replace(/[#=]/g, String.raw`\$&`) + ' ]+$'), '');
		let contentOffset = offsets[2];

		// Adjust offset for leading whitespace removed by trim
		const leadingSpaces = mContent.length - mContent.replace(/^\s+/, '').length;
		contentOffset += leadingSpaces;

		return new HeadingNode(
			context.parseInline(mContent.trim(), contentOffset),
			level,
			HeadingType.Surrounded,
			Modifier.parse(mMod, offsets[3] ?? null),
			{ offset: offsets[0], length: matches[0].length },
		);
	}
}


HeadingModule.Dynamic = 1; // auto-leveling
HeadingModule.Fixed = 2; // fixed-leveling
